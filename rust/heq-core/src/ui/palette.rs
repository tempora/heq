pub type Rgba = [u8; 4];

const fn rgb(r: u8, g: u8, b: u8) -> Rgba {
    [r, g, b, 0xFF]
}

const fn rgba(r: u8, g: u8, b: u8, a: u8) -> Rgba {
    [r, g, b, a]
}

pub const BAND_WHEEL: [Rgba; 12] = [
    rgb(0xFF, 0x7A, 0x52), // ember
    rgb(0xFF, 0xA0, 0x3C), // orange
    rgb(0xF5, 0xC7, 0x4C), // amber
    rgb(0xD8, 0xCE, 0x62), // wheat
    rgb(0xAE, 0xC2, 0x63), // olive
    rgb(0x8F, 0xB8, 0x82), // sage
    rgb(0xC9, 0x8E, 0x5A), // caramel
    rgb(0xE0, 0x8B, 0x6B), // clay
    rgb(0xF0, 0x92, 0x8E), // salmon
    rgb(0xE8, 0x7E, 0xA8), // rose
    rgb(0xC2, 0x86, 0xB8), // mauve
    rgb(0xB8, 0x6F, 0x6F), // brick
];

pub fn band_color(index: usize) -> Rgba {
    BAND_WHEEL[index % BAND_WHEEL.len()]
}

pub fn with_alpha(c: Rgba, a: u8) -> Rgba {
    [c[0], c[1], c[2], a]
}

